"""Tables of the evaluation, rebuilt from the saved predictions (CLAUDE.md §10).

Run with ``python -m t2sql.eval.report [--split val]``. Every scored run of the split found in
``results/predictions`` becomes one configuration (model + mode). Nothing is generated: the
numbers are recomputed from the per-example rows, so the report can never disagree with them.
"""

import argparse
import json
from collections import Counter
from pathlib import Path
from typing import Any

from t2sql.eval.run import MODES, ROOT, read_jsonl, run_files, run_name, summarize

PREDICTIONS_DIR = ROOT / "results" / "predictions"
REPORT_DIR = ROOT / "results"
FIRST_OUTCOMES = ("correct", "wrong_result")  # then the failures, most frequent first
LATENCY_NOTE = (
    "GPU s/example: time of a batch of 8 questions on the GPU of the run, divided by 8. "
    "It compares configurations; it is not the wait of one user (the demo runs on a CPU)."
)


def load_runs(directory: Path, split: str) -> list[dict[str, Any]]:
    """Every scored run of ``split``: its settings (from the summary) and its rows.

    Ordered by model, then zero-shot before few-shot, whatever the file names.
    """
    runs = []
    for summary_path in directory.glob(f"*_{split}_*.summary.json"):
        settings = json.loads(summary_path.read_text(encoding="utf-8"))
        rows = read_jsonl(run_files(directory, run_name(settings))["predictions"])
        runs.append({"model": settings["model"], "mode": settings["mode"], "rows": rows})
    return sorted(runs, key=lambda run: (run["model"], MODES.index(run["mode"])))


def label(run: dict[str, Any]) -> str:
    """Short name of a configuration: model without its organisation, and mode."""
    return f"{run['model'].split('/')[-1]} {run['mode']}"


def percent(value: float) -> str:
    return f"{100 * value:.1f} %"


def headline_table(runs: list[dict[str, Any]]) -> str:
    """One line per configuration: the headline numbers of CLAUDE.md §10."""
    lines = [
        "| Configuration | Examples | Execution accuracy | Valid SQL | GPU s/example | Tokens |",
        "|---|---:|---:|---:|---:|---:|",
    ]
    for run in runs:
        s = summarize(run["rows"])
        lines.append(
            f"| {label(run)} | {s['examples']} "
            f"| {percent(s['execution_accuracy'])} | {percent(s['valid_sql_rate'])} "
            f"| {s['mean_latency_s']:.2f} | {s['mean_output_tokens']:.0f} |"
        )
    return "\n".join(lines)


def breakdown_table(runs: list[dict[str, Any]], key: str) -> str:
    """Correct answers per value of ``key`` (family, lang, template_id), one column per run."""
    values = sorted({row[key] for run in runs for row in run["rows"]})
    lines = [
        f"| {key} | n | " + " | ".join(label(run) for run in runs) + " |",
        "|---|---:|" + "---:|" * len(runs),
    ]
    for value in values:
        cells, n = [], 0
        for run in runs:
            rows = [row for row in run["rows"] if row[key] == value]
            n = n or len(rows)
            correct = sum(row["outcome"] == "correct" for row in rows)
            cells.append(f"{correct} ({percent(correct / len(rows))})" if rows else "-")
        lines.append(f"| {value} | {n} | " + " | ".join(cells) + " |")
    return "\n".join(lines)


def outcomes_table(runs: list[dict[str, Any]]) -> str:
    """How many examples ended in each outcome: the automatic error taxonomy."""
    counts = [Counter(row["outcome"] for row in run["rows"]) for run in runs]
    total = sum(counts, Counter())
    failures = [kind for kind, _ in total.most_common() if kind not in FIRST_OUTCOMES]
    lines = [
        "| Outcome | " + " | ".join(label(run) for run in runs) + " |",
        "|---|" + "---:|" * len(runs),
    ]
    for kind in [*FIRST_OUTCOMES, *failures]:
        lines.append(f"| {kind} | " + " | ".join(str(c[kind]) for c in counts) + " |")
    return "\n".join(lines)


def report(runs: list[dict[str, Any]], split: str) -> str:
    """The whole report of one split, as Markdown."""
    return "\n\n".join(
        [
            f"# Evaluation report: {split} split",
            "Generated by `python -m t2sql.eval.report` from `results/predictions`.",
            "## Headline",
            headline_table(runs),
            LATENCY_NOTE,
            "## By family (correct answers)",
            breakdown_table(runs, "family"),
            "## By language (correct answers)",
            breakdown_table(runs, "lang"),
            "## Outcomes",
            outcomes_table(runs),
        ]
    )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--split", default="val")
    args = parser.parse_args()
    runs = load_runs(PREDICTIONS_DIR, args.split)
    if not runs:
        raise SystemExit(f"no scored run of split {args.split!r} in {PREDICTIONS_DIR}")
    path = REPORT_DIR / f"report_{args.split}.md"
    path.write_text(report(runs, args.split) + "\n", encoding="utf-8")
    print(f"report: {path}")


if __name__ == "__main__":
    main()
